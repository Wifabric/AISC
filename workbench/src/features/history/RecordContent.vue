<script setup lang="ts">
import { computed, nextTick, onBeforeUnmount, ref, watch } from "vue";
import { useI18n } from "vue-i18n";
import type { ConversationAttachment } from "../../types";
import { useWorkspaceExplorerStore } from "../../stores/workspaceExplorer";
import { recordLink } from "./conversationReading";
import { renderRecordMarkdown } from "./recordMarkdown";
import "katex/dist/katex.min.css";

const props = defineProps<{ text: string; attachments?: ConversationAttachment[]; workspace: string }>();
const { t } = useI18n();
const explorer = useWorkspaceExplorerStore();
const body = ref<HTMLElement | null>(null);
const error = ref("");
const imageSources = ref<Record<number, string>>({});
const imageErrors = ref<Record<number, boolean>>({});
const html = computed(() => renderRecordMarkdown(props.text));
let generation = 0;
onBeforeUnmount(() => { generation++; });

function directImage(url: string): string | null {
  if (/^data:image\/(?:png|jpeg|gif|webp);base64,[a-z0-9+/=\s]+$/i.test(url) && url.length <= 12_000_000) return url;
  return recordLink(url, props.workspace)?.kind === "web" ? url : null;
}

async function imageUrl(url: string, workspace: string): Promise<string> {
  const direct = directImage(url);
  if (direct) return direct;
  const link = recordLink(url, workspace);
  if (link?.kind !== "file") throw new Error("unavailable image");
  return explorer.readRecordImage(link.path, workspace);
}

watch(() => [props.text, props.attachments, props.workspace], async () => {
  const current = ++generation;
  const workspace = props.workspace;
  error.value = ""; imageSources.value = {}; imageErrors.value = {};
  await nextTick();
  if (current !== generation) return;
  const root = body.value;
  // Copy controls are generated by us, never from transcript HTML.
  root?.querySelectorAll("pre").forEach(pre => {
    if (pre.querySelector(".record-code-copy")) return;
    const button = document.createElement("button");
    button.type = "button"; button.className = "record-code-copy";
    button.textContent = t("history.viewer.copyCode");
    pre.prepend(button);
  });
  const inline = [...(root?.querySelectorAll<HTMLImageElement>("img[data-record-image]") ?? [])];
  await Promise.allSettled([
    ...inline.map(async img => {
      try {
        const src = await imageUrl(img.dataset.recordImage ?? "", workspace);
        if (current === generation && img.isConnected) img.src = src;
      } catch { if (current === generation) img.alt = t("history.viewer.imageUnavailable") + ": " + img.alt; }
    }),
    ...(props.attachments ?? []).map(async (attachment, i) => {
      if (attachment.kind !== "image" || !attachment.url) return;
      try {
        const src = await imageUrl(attachment.url, workspace);
        if (current === generation) imageSources.value = { ...imageSources.value, [i]: src };
      } catch { if (current === generation) imageErrors.value = { ...imageErrors.value, [i]: true }; }
    }),
  ]);
}, { immediate: true });

async function open(url: string) {
  error.value = "";
  try { await explorer.openRecordLink(url, props.workspace); }
  catch { error.value = t("history.viewer.linkUnavailable"); }
}

async function click(event: MouseEvent) {
  const element = event.target instanceof Element ? event.target : null;
  const copy = element?.closest<HTMLButtonElement>("button.record-code-copy");
  if (copy) {
    try { await explorer.copyRecordText(copy.parentElement?.querySelector("code")?.textContent ?? ""); copy.textContent = t("history.viewer.copied"); }
    catch { error.value = t("history.viewer.copyFailed"); }
    return;
  }
  const anchor = element?.closest<HTMLAnchorElement>("a");
  if (!anchor) return;
  event.preventDefault();
  const href = anchor.dataset.recordHref ?? anchor.getAttribute("href") ?? "";
  const link = recordLink(href, props.workspace);
  if (link?.kind === "anchor") {
    const el = [...(body.value?.querySelectorAll<HTMLElement>("[id]") ?? [])].find(e => e.id === link.id);
    el?.scrollIntoView?.({ block: "center" }); el?.focus();
  } else await open(href);
}
</script>

<template>
  <div class="record-content">
    <div ref="body" class="record-markdown" @click="click" v-html="html" />
    <div v-if="attachments?.length" class="record-attachments">
      <figure v-for="(attachment, i) in attachments" :key="i" class="record-attachment">
        <template v-if="attachment.kind === 'image'">
          <img v-if="imageSources[i] && !imageErrors[i]" :src="imageSources[i]" :alt="attachment.name" loading="lazy" referrerpolicy="no-referrer" @error="imageErrors[i] = true" />
          <span v-else>{{ imageErrors[i] || !attachment.url ? t('history.viewer.imageUnavailable') : t('history.viewer.loading') }}</span>
        </template>
        <figcaption>
          <button v-if="attachment.url && !attachment.url.startsWith('data:')" type="button" @click="open(attachment.url)">{{ attachment.name }}</button>
          <span v-else>{{ attachment.name }}</span>
        </figcaption>
        <details v-if="attachment.detail"><summary>{{ t('history.viewer.attachmentDetails') }}</summary><pre>{{ attachment.detail }}</pre></details>
      </figure>
    </div>
    <p v-if="error" class="record-error" role="status">{{ error }}</p>
  </div>
</template>

